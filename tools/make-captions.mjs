// make-captions.mjs
// Builds WebVTT captions for the video résumé from the TurboScribe export.
//
// The export gives coarse blocks (0:00 - 0:46) rather than per-sentence timing.
// This splits each block into sentences and distributes the block's duration
// across them in proportion to their character count, which is a decent proxy
// for speaking time at a steady pace.
//
// LIMITATION, stated plainly: timing inside a block is interpolated, not
// measured. Short blocks land within about a second. The long 1:52-3:47 block
// can drift by several seconds mid-way. That is materially better than no
// captions, and it is worth a manual pass before anyone treats it as exact.
//
// Corrections are applied from a table rather than by hand-editing the output,
// so re-running never silently reverts them. Every entry is a word the
// transcriber misheard that the résumé disambiguates.
//
// Run: node tools/make-captions.mjs

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(homedir(), 'Downloads', 'Rheana Mindo Video Resume.txt');
const outDir = join(here, '../apps/web/public/media');

// [pattern, replacement, why]
const CORRECTIONS = [
  [/Rianna M\. Mindo/g, 'Rheana M. Mindo', 'speaker name'],
  [/Rihanna Mindo in 3D and I love/g, "Rheana Mindo, and I'd love", 'speaker name; "in 3D" is a mishearing'],
  [/Rihanna|Rianna/g, 'Rheana', 'speaker name'],
  [/I believe text should be/g, 'I believe tech should be', 'tech, not text'],
  [/DOSDSA and UP's last grant scholarships/g, 'DOST-SEI and UP SLAS scholarships', 'named on the resume'],
  [/At ASUS,/g, 'At Azeus,', 'Azeus Systems, the internship employer'],
  [/drug chatbot/g, 'RAG chatbot', 'retrieval-augmented generation'],
  [/Longchain/g, 'LangChain', 'library name'],
  [/codewords platform/g, 'Code Wars platform', 'the COSS Code Wars contest platform'],
  [/As Kaeban's treasurer/g, "As Kaiban's treasurer", 'UPLB Kaiban'],
  [/I don't run on pathing/g, "I don't run on caffeine", 'caffeine'],
];

const raw = await readFile(source, 'utf8');

// Drop the transcription-service watermark lines.
const cleaned = raw
  .split('\n')
  .filter(line => !/TurboScribe/i.test(line))
  .join('\n');

const applied = [];
let text = cleaned;
for (const [pattern, replacement, why] of CORRECTIONS) {
  const before = text;
  text = text.replace(pattern, replacement);
  if (text !== before) applied.push(`${pattern.source} -> ${replacement}  (${why})`);
}

const toSeconds = stamp => {
  const [m, s] = stamp.split(':').map(Number);
  return m * 60 + s;
};

const stamp = seconds => {
  const h = Math.floor(seconds / 3600);
  const m = Math.floor((seconds % 3600) / 60);
  const s = seconds % 60;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${s.toFixed(3).padStart(6, '0')}`;
};

// Parse "(0:00 - 0:46)" headers and the prose that follows each.
const BLOCK = /\((\d+:\d{2})\s*-\s*(\d+:\d{2})\)([\s\S]*?)(?=\(\d+:\d{2}\s*-|\s*$)/g;
const blocks = [];
let m;
while ((m = BLOCK.exec(text)) !== null) {
  const body = m[3].replace(/\s+/g, ' ').trim();
  if (body) blocks.push({ start: toSeconds(m[1]), end: toSeconds(m[2]), body });
}

if (!blocks.length) throw new Error('no timed blocks found in the transcript');

const cues = [];
for (const block of blocks) {
  // Keep the terminator on the sentence so cues read naturally.
  const sentences = block.body.match(/[^.!?]+[.!?]+["']?|\S+$/g) ?? [block.body];
  const total = sentences.reduce((n, s) => n + s.trim().length, 0);
  const span = block.end - block.start;

  let cursor = block.start;
  sentences.forEach((sentence, i) => {
    const s = sentence.trim();
    if (!s) return;
    const share = (s.length / total) * span;
    const start = cursor;
    // Last cue in a block snaps to the block end so rounding cannot leave a gap.
    const end = i === sentences.length - 1 ? block.end : Math.min(block.end, cursor + share);
    cursor = end;
    if (end - start < 0.4) return;
    cues.push({ start, end, text: s });
  });
}

const vtt = [
  'WEBVTT',
  '',
  'NOTE',
  'Captions for Rheana Mindo\'s video resume.',
  'Block timings come from the transcript export; sentence timings within each',
  'block are interpolated by length. Generated by tools/make-captions.mjs.',
  '',
  ...cues.flatMap((cue, i) => [
    String(i + 1),
    `${stamp(cue.start)} --> ${stamp(cue.end)}`,
    // Wrap long cues onto two lines; three-line captions are hard to read.
    cue.text.length > 78
      ? cue.text.replace(new RegExp(`(.{1,${Math.ceil(cue.text.length / 2)}})(\\s|$)`), '$1\n')
      : cue.text,
    '',
  ]),
].join('\n');

await mkdir(outDir, { recursive: true });
await writeFile(join(outDir, 'rheana-mindo-video-resume.en.vtt'), vtt);

console.log(`blocks: ${blocks.length}   cues: ${cues.length}   duration: ${stamp(blocks.at(-1).end)}`);
console.log('\ncorrections applied:');
for (const line of applied) console.log('  ' + line);
console.log(`\nwrote apps/web/public/media/rheana-mindo-video-resume.en.vtt`);
